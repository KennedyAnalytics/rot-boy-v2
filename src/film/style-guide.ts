export const styleRules = `Motion style rules. These constrain quality. They do not pick the scene.

- The picture shows an action or a change of state. A ledger of the ending is not a process.
- One recognizable object persists through the chapter. Its state advances when the narration advances, not before.
- One thing dominates. Do not repeat the same fact in the stage and the callout.
- Essential labels must stay readable at phone width. Shorten on a word boundary without dropping "not", a number, a name, or the condition.
- A pill binds a term. A card explains a referent. A stamp marks a result that has already happened.
- Cause, then consequence. Do not show a result on the opening beat of the chapter if a later sentence is what causes it.
- Green and red mean a real pass or fail. Do not mark a hypothetical as a completed success.
- The presenter supports the explanation. lead carries an opening, a turn, or the close. beside is ordinary teaching. away when the stage needs the width.
- A recap reuses the parts and the case's actual final state. It does not invent a new object or reset the case to waiting.
- A conditional ("if") is a branch, not a rewrite of what happened.
- Captions carry the voice. The stage must still make sense if the caption is ignored.`;